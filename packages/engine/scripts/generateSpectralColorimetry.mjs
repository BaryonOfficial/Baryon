import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";
import process from "node:process";
// Historical design seed only. The engine ships the generated arc-length fit;
// this offline curve is retained so its coefficients remain reproducible.
const designSeed = {
  chromaticityBase: Object.freeze([
    1.2084912873873068, 0.9199340128364738, 1.1791959324212258,
  ]),
  cosineAxis: Object.freeze([
    0.9287534381828134, -0.3515448914639626, 0.7475335930382262,
  ]),
  sineAxis: Object.freeze([
    0.931821448822781, -0.16994322376052778, -1.0604133848503292,
  ]),
  secondCosineAxis: Object.freeze([
    0.04052905162636272, -0.01495270590886131, 0.028776992939790743,
  ]),
  secondSineAxis: Object.freeze([
    0.17894853445334638, -0.03314023391328511, -0.198650458864265,
  ]),
};
function designChromaticity(direction) {
  const magnitude = Math.hypot(...direction);
  const [x, y] = direction.map((v) => v / magnitude);
  const {
    chromaticityBase,
    cosineAxis,
    sineAxis,
    secondCosineAxis,
    secondSineAxis,
  } = designSeed;
  return chromaticityBase.map(
    (base, c) =>
      base +
      cosineAxis[c] * x +
      sineAxis[c] * y +
      secondCosineAxis[c] * (x * x - y * y) +
      secondSineAxis[c] * (2 * x * y),
  );
}

// Reparameterize the existing curve by cumulative OKLab distance at its
// reference luminance. Phase zero stays anchored; the hue order is unchanged.
const count = 8192,
  order = 8;
const rgbAt = (phase) => designChromaticity([Math.cos(phase), Math.sin(phase)]);
function lab(rgb) {
  const [r, g, b] = rgb.map((v) => v * 0.343);
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
}
const arc = [0];
let previous = lab(rgbAt(0));
for (let i = 1; i <= count; i++) {
  const next = lab(rgbAt((i / count) * 2 * Math.PI));
  arc.push(arc.at(-1) + Math.hypot(...next.map((v, k) => v - previous[k])));
  previous = next;
}
const samples = [];
let cursor = 1;
for (let i = 0; i < count; i++) {
  const distance = (arc.at(-1) * i) / count;
  while (arc[cursor] < distance) cursor++;
  const fraction =
    (distance - arc[cursor - 1]) / (arc[cursor] - arc[cursor - 1]);
  samples.push(rgbAt(((cursor - 1 + fraction) / count) * 2 * Math.PI));
}
const mean = [0, 0, 0],
  cosine = [],
  sine = [];
for (let k = 0; k < order; k++) {
  cosine.push([0, 0, 0]);
  sine.push([0, 0, 0]);
}
for (let i = 0; i < count; i++)
  for (let c = 0; c < 3; c++) {
    mean[c] += samples[i][c] / count;
    for (let k = 1; k <= order; k++) {
      cosine[k - 1][c] +=
        (2 * samples[i][c] * Math.cos(((k * i) / count) * 2 * Math.PI)) / count;
      sine[k - 1][c] +=
        (2 * samples[i][c] * Math.sin(((k * i) / count) * 2 * Math.PI)) / count;
    }
  }
// Pin Rec.709 luminance exactly, independently of fitting roundoff.
const luminance = (v) => 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2];
const project = (v, target) => v.map((x) => x + target - luminance(v));
const coefficients = {
  base: project(mean, 1),
  cosine: cosine.map((v) => project(v, 0)),
  sine: sine.map((v) => project(v, 0)),
};
const source = await format(
  "// Generated by scripts/generateSpectralColorimetry.mjs. Perceptually balanced cyclic palette.\nexport const SPECTRAL_COLORIMETRY_COEFFICIENTS = " +
    JSON.stringify(coefficients, null, 2) +
    ";\n",
  { parser: "babel" },
);
const file = new URL(
  "../src/core/raymarch/spectralColorimetryCoefficients.js",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(file, "utf8")) !== source)
    throw new Error("Spectral colorimetry coefficients are stale");
} else await writeFile(file, source);
